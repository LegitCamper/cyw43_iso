//! Minimal LE 1M broadcast discovery PDUs, without a radio scheduler.
//!
//! Core 6.0 Vol 6 Part B sections 2.3.1.5..7 and 2.3.4; cross-checked with
//! Zephyr v4.2.0 `pdu_adv_aux_ptr`, `pdu_adv_sync_info`, and ADI macros.
//! Returned bytes include the two-octet PDU header, but exclude preamble,
//! Access Address, CRC, and whitening. Primary and auxiliary advertising use
//! AA `0x8e89bed6` and `CRCInit` `0x555555`; periodic packets use `SyncInfo`.
//! Caller supplies physical entropy, device-wide address uniqueness, accurate
//! packet-start offsets, CSA #2 periodic channels, and event-counter updates.

use crate::{
    bis::{BisParameters, validate_access_address},
    broadcast::{BigInfo, BroadcastError, SingleBisBase, broadcast_audio_announcement},
};
use alloc::{vec, vec::Vec};
use core::fmt;

/// Aux/Sync offset, quantized down from the actual packet-start separation.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct AdvertisingOffset {
    /// 13-bit nonzero offset; zero's incomplete-information meaning is omitted.
    pub value: u16,
    pub units_300_us: bool,
}

impl AdvertisingOffset {
    /// Returns the start of the encoded window; its width is one offset unit.
    ///
    /// # Errors
    /// Rejects zero, overflow, or 300 us units below the mandatory threshold.
    pub fn microseconds(self) -> Result<u32, AdvertisingError> {
        let us = u32::from(self.value) * if self.units_300_us { 300 } else { 30 };
        if self.value == 0 || self.value > 0x1fff || (self.units_300_us && us < 245_700) {
            return Err(AdvertisingError::Field);
        }
        Ok(us)
    }
}

/// Identity shared by primary and auxiliary advertisements.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct AdvertisingSet {
    /// Address in least-significant-octet-first packet order.
    pub address: [u8; 6],
    /// False for public addresses; true supports static random addresses only.
    pub random_static: bool,
    pub sid: u8,
    /// 12-bit Advertising DID; change when advertising data changes.
    pub did: u16,
    /// Random 24-bit Broadcast ID, generated by the caller.
    pub broadcast_id: u32,
}

impl AdvertisingSet {
    fn validate(&self) -> Result<(), AdvertisingError> {
        let low = self.address[..5].iter();
        let random_all_zero = low.clone().all(|b| *b == 0) && self.address[5].trailing_zeros() >= 6;
        let random_all_one = low.clone().all(|b| *b == 0xff) && self.address[5] & 0x3f == 0x3f;
        if self.sid > 15
            || self.did > 0x0fff
            || self.broadcast_id > 0x00ff_ffff
            || (self.random_static
                && (self.address[5] & 0xc0 != 0xc0 || random_all_zero || random_all_one))
        {
            return Err(AdvertisingError::Field);
        }
        Ok(())
    }

    fn adi(&self) -> [u8; 2] {
        (self.did | (u16::from(self.sid) << 12)).to_le_bytes()
    }

    /// Builds primary `ADV_EXT_IND` with ADI and a LE 1M `AuxPtr`.
    ///
    /// `AdvA` occurs only in the auxiliary PDU, as Core table 2.5 requires.
    /// Send on a primary advertising channel, using the advertising AA/`CRCInit`.
    ///
    /// # Errors
    /// Rejects invalid identity/channel/offset or an offset below packet airtime
    /// plus the 300 us minimum AUX frame space.
    pub fn primary_pdu(
        &self,
        auxiliary_channel: u8,
        offset: AdvertisingOffset,
        clock_accuracy_50_ppm: bool,
    ) -> Result<Vec<u8>, AdvertisingError> {
        self.validate()?;
        if auxiliary_channel > 36 {
            return Err(AdvertisingError::Field);
        }
        // Nine PDU octets + eight LE 1M preamble/AA/CRC octets = 136 us.
        if offset.microseconds()? < 136 + 300 {
            return Err(AdvertisingError::Timing);
        }
        let mut header = vec![0x18];
        header.extend_from_slice(&self.adi());
        header.push(
            auxiliary_channel
                | (u8::from(clock_accuracy_50_ppm) << 6)
                | (u8::from(offset.units_300_us) << 7),
        );
        header.extend_from_slice(&offset.value.to_le_bytes());
        packet(false, &header, &[])
    }

    /// Builds `AUX_ADV_IND` with `AdvA`, matching ADI, and `SyncInfo`.
    ///
    /// `AdvData` carries Broadcast Audio Announcement service data. The entire
    /// discovery train uses LE 1M; transmit this on the primary packet's `AuxPtr`
    /// channel, still using the advertising AA and `CRCInit`.
    ///
    /// # Errors
    /// Rejects invalid identity/synchronization fields or overlapping packets.
    pub fn auxiliary_pdu(&self, sync: &SyncInfo) -> Result<Vec<u8>, AdvertisingError> {
        self.validate()?;
        let mut header = vec![0x29];
        header.extend_from_slice(&self.address);
        header.extend_from_slice(&self.adi());
        header.extend_from_slice(&sync.encode()?);
        let ad =
            broadcast_audio_announcement(self.broadcast_id).map_err(AdvertisingError::Broadcast)?;
        let bytes = packet(self.random_static, &header, &ad)?;
        if sync.offset.microseconds()? < airtime_us(&bytes)? {
            return Err(AdvertisingError::Timing);
        }
        Ok(bytes)
    }
}

/// Synchronization information for one LE 1M periodic advertising train.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SyncInfo {
    pub offset: AdvertisingOffset,
    /// Units of 1.25 ms, range 6..=65535.
    pub interval: u16,
    pub channel_map: [u8; 5],
    /// Core SCA encoding 0..=7 (500 ppm down to 20 ppm).
    pub sleep_clock_accuracy: u8,
    pub access_address: u32,
    /// 24-bit CRC initialization value.
    pub crc_init: u32,
    pub event_counter: u16,
}

impl SyncInfo {
    /// Encodes the 18-byte field; Offset Adjust and RFU remain zero.
    ///
    /// # Errors
    /// Rejects invalid offset, interval, map, SCA, Access Address, or `CRCInit`.
    pub fn encode(&self) -> Result<[u8; 18], AdvertisingError> {
        self.offset.microseconds()?;
        if self.interval < 6
            || self.sleep_clock_accuracy > 7
            || self.crc_init > 0x00ff_ffff
            || self.channel_map[4] & 0xe0 != 0
            || self.channel_map.iter().map(|b| b.count_ones()).sum::<u32>() < 2
        {
            return Err(AdvertisingError::Field);
        }
        validate_access_address(self.access_address, false)
            .map_err(|_| AdvertisingError::Identity)?;
        let mut bytes = [0; 18];
        let offset = self.offset.value | (u16::from(self.offset.units_300_us) << 13);
        bytes[..2].copy_from_slice(&offset.to_le_bytes());
        bytes[2..4].copy_from_slice(&self.interval.to_le_bytes());
        bytes[4..9].copy_from_slice(&self.channel_map);
        bytes[8] |= self.sleep_clock_accuracy << 5;
        bytes[9..13].copy_from_slice(&self.access_address.to_le_bytes());
        bytes[13..16].copy_from_slice(&self.crc_init.to_le_bytes()[..3]);
        bytes[16..18].copy_from_slice(&self.event_counter.to_le_bytes());
        Ok(bytes)
    }

    /// Builds `AUX_SYNC_IND`: `BIGInfo` in ACAD, single-BIS BASE in `AdvData`.
    ///
    /// Use this train's AA/`CRCInit` and CSA #2 channel for `event_counter`.
    /// The periodic interval and BIG interval may differ. Caller refreshes
    /// `BIGInfo`'s offset/count to identify an actual future BIG anchor.
    ///
    /// # Errors
    /// Rejects invalid fields, multiple BISes, insufficient SDU capacity,
    /// reused BIG identities, or a packet overlapping its BIG/periodic anchor.
    pub fn periodic_pdu(
        &self,
        big: &BigInfo,
        base: &SingleBisBase,
    ) -> Result<Vec<u8>, AdvertisingError> {
        self.encode()?;
        big.validate().map_err(AdvertisingError::Broadcast)?;
        if big.num_bis != 1 {
            return Err(AdvertisingError::Field);
        }
        let sdu_length = base
            .config
            .sdu_length()
            .map_err(|_| AdvertisingError::Field)?;
        if sdu_length > usize::from(big.max_sdu) {
            return Err(AdvertisingError::Field);
        }
        for bis in 0..=1 {
            let identity = BisParameters::derive(big.seed_access_address, big.base_crc_init, bis)
                .map_err(|_| AdvertisingError::Identity)?;
            if self.access_address == identity.access_address {
                return Err(AdvertisingError::Identity);
            }
        }
        // ponytail: no ADI/CTE/fragmentation in periodic packets; add when one BASE exceeds a PDU.
        let mut header = vec![0];
        header.extend_from_slice(&big.acad().map_err(AdvertisingError::Broadcast)?);
        let data = base
            .periodic_advertising_data()
            .map_err(AdvertisingError::Broadcast)?;
        let bytes = packet(false, &header, &data)?;
        let duration = airtime_us(&bytes)?;
        let big_offset = u32::from(big.offset) * if big.offset_units_300_us { 300 } else { 30 };
        if big_offset < duration || duration >= u32::from(self.interval) * 1250 {
            return Err(AdvertisingError::Timing);
        }
        Ok(bytes)
    }
}

fn packet(random: bool, header: &[u8], data: &[u8]) -> Result<Vec<u8>, AdvertisingError> {
    let header_length = u8::try_from(header.len()).map_err(|_| AdvertisingError::Field)?;
    let length =
        u8::try_from(1 + header.len() + data.len()).map_err(|_| AdvertisingError::Field)?;
    if header_length > 63 {
        return Err(AdvertisingError::Field);
    }
    let mut bytes = vec![7 | (u8::from(random) << 6), length, header_length];
    bytes.extend_from_slice(header);
    bytes.extend_from_slice(data);
    Ok(bytes)
}

fn airtime_us(pdu: &[u8]) -> Result<u32, AdvertisingError> {
    Ok((u32::try_from(pdu.len()).map_err(|_| AdvertisingError::Field)? + 8) * 8)
}

/// Invalid discovery input or incompatible packet timing.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AdvertisingError {
    Field,
    Identity,
    Timing,
    Broadcast(BroadcastError),
}

impl fmt::Display for AdvertisingError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "broadcast advertising error: {self:?}")
    }
}

impl core::error::Error for AdvertisingError {}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{broadcast::BroadcastPhy, le_audio::Lc3Config};

    fn advertising() -> AdvertisingSet {
        AdvertisingSet {
            address: [1, 2, 3, 4, 5, 0xc6],
            random_static: true,
            sid: 3,
            did: 0xabc,
            broadcast_id: 0x12_3456,
        }
    }

    fn sync() -> SyncInfo {
        SyncInfo {
            offset: AdvertisingOffset {
                value: 125,
                units_300_us: false,
            },
            interval: 8,
            channel_map: [255, 255, 255, 255, 31],
            sleep_clock_accuracy: 0,
            access_address: 0x1234_5678,
            crc_init: 0xab_cdef,
            event_counter: 0x1234,
        }
    }

    fn audio() -> (BigInfo, SingleBisBase) {
        (
            BigInfo {
                offset: 125,
                offset_units_300_us: false,
                iso_interval: 8,
                num_bis: 1,
                nse: 1,
                bn: 1,
                sub_interval_us: 500,
                pto: 0,
                bis_spacing_us: 500,
                irc: 1,
                max_pdu: 26,
                seed_access_address: 0x8c88_bed6,
                sdu_interval_us: 10000,
                max_sdu: 26,
                base_crc_init: 0x1234,
                channel_map: [255, 255, 255, 255, 31],
                phy: BroadcastPhy::Le1M,
                payload_count: 0,
                framed: false,
            },
            SingleBisBase {
                presentation_delay_us: 40000,
                config: Lc3Config::parse(&[2, 1, 1, 2, 2, 1, 3, 4, 26, 0]).unwrap(),
                streaming_contexts: 4,
            },
        )
    }

    #[test]
    fn discovery_pdus_match_compiled_zephyr_layouts() {
        // Zephyr v4.2.0 pdu.h structures, ADI/SyncInfo macros and BIGInfo
        // util_set_bits compiled on a little-endian host. Fixtures are not
        // entropy sources and must not become fixed production identities.
        // 3750 us links fit both 30 us wire units and the CYW43 625 us timer.
        let primary = advertising()
            .primary_pdu(
                17,
                AdvertisingOffset {
                    value: 125,
                    units_300_us: false,
                },
                true,
            )
            .unwrap();
        assert_eq!(
            primary,
            [0x07, 0x07, 0x06, 0x18, 0xbc, 0x3a, 0x51, 0x7d, 0x00]
        );
        assert_eq!(airtime_us(&primary).unwrap(), 136);
        let auxiliary = advertising().auxiliary_pdu(&sync()).unwrap();
        assert_eq!(
            auxiliary,
            [
                0x47, 0x23, 0x1b, 0x29, 0x01, 0x02, 0x03, 0x04, 0x05, 0xc6, 0xbc, 0x3a, 0x7d, 0x00,
                0x08, 0x00, 0xff, 0xff, 0xff, 0xff, 0x1f, 0x78, 0x56, 0x34, 0x12, 0xef, 0xcd, 0xab,
                0x34, 0x12, 0x06, 0x16, 0x52, 0x18, 0x56, 0x34, 0x12,
            ]
        );
        assert_eq!(airtime_us(&auxiliary).unwrap(), 360);
        let (big, base) = audio();
        let periodic = sync().periodic_pdu(&big, &base).unwrap();
        assert_eq!(
            periodic,
            [
                0x07, 0x45, 0x24, 0x00, 0x22, 0x2c, 0x7d, 0x00, 0x04, 0x08, 0x21, 0xf4, 0x01, 0x00,
                0xf4, 0x01, 0x10, 0x1a, 0x00, 0xd6, 0xbe, 0x88, 0x8c, 0x10, 0x27, 0xa0, 0x01, 0x34,
                0x12, 0xff, 0xff, 0xff, 0xff, 0x1f, 0x00, 0x00, 0x00, 0x00, 0x00, 0x1f, 0x16, 0x51,
                0x18, 0x40, 0x9c, 0x00, 0x01, 0x01, 0x06, 0x00, 0x00, 0x00, 0x00, 0x0a, 0x02, 0x01,
                0x01, 0x02, 0x02, 0x01, 0x03, 0x04, 0x1a, 0x00, 0x04, 0x03, 0x02, 0x04, 0x00, 0x01,
                0x00,
            ]
        );
        assert_eq!(airtime_us(&periodic).unwrap(), 632);
        assert_eq!(BigInfo::parse(&periodic[6..39]).unwrap(), big);
        assert_eq!(&periodic[39..], base.periodic_advertising_data().unwrap());
    }

    #[test]
    fn offsets_and_sca_use_distinct_bit_positions() {
        let long = AdvertisingOffset {
            value: 819,
            units_300_us: true,
        };
        assert_eq!(long.microseconds().unwrap(), 245_700);
        let mut s = sync();
        s.offset = long;
        s.sleep_clock_accuracy = 5;
        let encoded = s.encode().unwrap();
        assert_eq!(&encoded[..2], &[0x33, 0x23]);
        assert_eq!(encoded[8], 0xbf);
        assert_eq!(
            &advertising().primary_pdu(17, long, true).unwrap()[6..],
            &[0xd1, 0x33, 3]
        );
        for offset in [
            AdvertisingOffset {
                value: 0,
                units_300_us: false,
            },
            AdvertisingOffset {
                value: 8192,
                units_300_us: false,
            },
            AdvertisingOffset {
                value: 818,
                units_300_us: true,
            },
        ] {
            assert_eq!(offset.microseconds(), Err(AdvertisingError::Field));
        }
    }

    #[test]
    fn invalid_identity_sync_and_timing_are_rejected() {
        let changes: [fn(&mut SyncInfo); 6] = [
            |s| s.interval = 5,
            |s| s.channel_map = [1, 0, 0, 0, 0],
            |s| s.channel_map[4] = 0x20,
            |s| s.sleep_clock_accuracy = 8,
            |s| s.crc_init = 1 << 24,
            |s| s.offset.value = 8192,
        ];
        for change in changes {
            let mut s = sync();
            change(&mut s);
            assert_eq!(s.encode(), Err(AdvertisingError::Field));
        }
        let mut s = sync();
        s.access_address = 0x8e89_bed6;
        assert_eq!(s.encode(), Err(AdvertisingError::Identity));
        let mut a = advertising();
        a.did = 4096;
        assert_eq!(a.auxiliary_pdu(&sync()), Err(AdvertisingError::Field));
        a = advertising();
        a.sid = 16;
        assert_eq!(a.auxiliary_pdu(&sync()), Err(AdvertisingError::Field));
        a = advertising();
        a.address = [0, 0, 0, 0, 0, 0xc0];
        assert_eq!(a.auxiliary_pdu(&sync()), Err(AdvertisingError::Field));
        a.address = [255; 6];
        assert_eq!(a.auxiliary_pdu(&sync()), Err(AdvertisingError::Field));
        let mut offset = AdvertisingOffset {
            value: 14,
            units_300_us: false,
        };
        assert_eq!(
            advertising().primary_pdu(17, offset, false),
            Err(AdvertisingError::Timing)
        );
        offset.value = 15;
        assert!(advertising().primary_pdu(17, offset, false).is_ok());
        assert_eq!(
            advertising().primary_pdu(37, offset, false),
            Err(AdvertisingError::Field)
        );
        s = sync();
        s.offset.value = 11;
        assert_eq!(
            advertising().auxiliary_pdu(&s),
            Err(AdvertisingError::Timing)
        );
        s.offset.value = 12;
        assert!(advertising().auxiliary_pdu(&s).is_ok());
    }

    #[test]
    fn periodic_packet_rejects_big_overlap_capacity_and_address_reuse() {
        let (mut big, base) = audio();
        big.offset = 21;
        assert_eq!(
            sync().periodic_pdu(&big, &base),
            Err(AdvertisingError::Timing)
        );
        big.offset = 22;
        assert!(sync().periodic_pdu(&big, &base).is_ok());
        big.max_sdu = 25;
        assert_eq!(
            sync().periodic_pdu(&big, &base),
            Err(AdvertisingError::Field)
        );
        big.max_sdu = 26;
        for bis in 0..=1 {
            let mut s = sync();
            s.access_address =
                BisParameters::derive(big.seed_access_address, big.base_crc_init, bis)
                    .unwrap()
                    .access_address;
            assert_eq!(s.periodic_pdu(&big, &base), Err(AdvertisingError::Identity));
        }
    }
}
